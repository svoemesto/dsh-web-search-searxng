/**
 * SearXNG `settings.yml` generation for the container this plugin owns.
 *
 * The file is written once and never overwritten: an owner who edits it keeps
 * their edits, and the secret key stays stable across plugin upgrades.
 *
 * @module dsh-web-search-searxng/settings
 */

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

/**
 * Render the settings file this plugin needs: JSON enabled (the provider reads
 * it), the limiter off (localhost-only instance), defaults for everything else.
 *
 * @param {{instanceName: string, secretKey: string}} input - instance label and secret.
 * @returns {string} YAML body.
 */
export function renderSettings({ instanceName, secretKey }) {
  return [
    '# Generated by dsh-web-search-searxng. Edits are kept: this file is never rewritten.',
    'use_default_settings: true',
    'general:',
    `  instance_name: ${JSON.stringify(instanceName)}`,
    'server:',
    `  secret_key: ${JSON.stringify(secretKey)}`,
    '  limiter: false',
    '  image_proxy: true',
    '  port: 8080',
    '  bind_address: "0.0.0.0"',
    'search:',
    '  safe_search: 0',
    '  formats:',
    '    - html',
    '    - json',
    '',
  ].join('\n')
}

/**
 * Ensure `<dataDir>/settings.yml` exists, generating it (and a fresh secret)
 * when it does not. Never rewrites an existing file.
 *
 * @param {string} dataDir - host directory mounted into the container.
 * @param {{instanceName: string, mkdir?: typeof fs.mkdirSync, exists?: typeof fs.existsSync, write?: typeof fs.writeFileSync}} input - label plus filesystem seams for tests.
 * @returns {{path: string, created: boolean}} the settings file and whether it was written now.
 */
export function ensureSettingsFile(dataDir, input) {
  const mkdir = input.mkdir ?? fs.mkdirSync
  const exists = input.exists ?? fs.existsSync
  const write = input.write ?? fs.writeFileSync
  const file = path.join(dataDir, 'settings.yml')
  mkdir(dataDir, { recursive: true })
  if (exists(file)) return { path: file, created: false }
  const secretKey = crypto.randomBytes(32).toString('hex')
  write(file, renderSettings({ instanceName: input.instanceName, secretKey }), { mode: 0o644 })
  return { path: file, created: true }
}
